export type GuestFixtureCoverageMinimums = {
  newGuests: number
  needsRecovery: number
  positiveFeedback: number
  offerNotRedeemed: number
  recentRedeemers: number
  dormantGuests: number
  newThisMonth: number
  marketingEligible: number
}

export function assertGuestFixtureCoverageMinimums(
  guests: OperatorGuestFixture[],
  nowMs: number,
  minimums: GuestFixtureCoverageMinimums
): void {
  const counts = {
    newGuests: countGuestsBySmartGroup(guests, "new-guests", nowMs),
    needsRecovery: countGuestsBySmartGroup(guests, "needs-recovery", nowMs),
    positiveFeedback: countGuestsBySmartGroup(guests, "positive-feedback", nowMs),
    offerNotRedeemed: countGuestsBySmartGroup(
      guests,
      "offer-not-redeemed",
      nowMs
    ),
    recentRedeemers: countGuestsBySmartGroup(guests, "recent-redeemers", nowMs),
    dormantGuests: countGuestsBySmartGroup(guests, "dormant-guests", nowMs),
    newThisMonth: guests.filter((guest) =>
      isWithinDaysUtc(guest.capturedAt, 30, nowMs)
    ).length,
    marketingEligible: guests.filter((guest) => guest.marketingEligible).length,
  }

  for (const [key, minimum] of Object.entries(minimums)) {
    const actual = counts[key as keyof typeof counts]
    if (actual < minimum) {
      throw new Error(
        `Fixture coverage for ${key}: expected >= ${minimum}, got ${actual}`
      )
    }
  }
}
