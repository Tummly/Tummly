function daysAgoIso(daysAgo: number, referenceMs: number): string {
  return new Date(referenceMs - daysAgo * 24 * 60 * 60 * 1000).toISOString()
}

function marketingEligible(label: GuestMarketingStatusLabel): boolean {
  return label.startsWith("Eligible —")
}

function buildGuestFromSeed(
  index: number,
  seed: GuestSeed,
  referenceMs: number
): OperatorGuestFixture {
  const id = `guest-${String(index + 1).padStart(3, "0")}`

  return {
    id,
    name: seed.name,
    email: seed.email,
    mobile: seed.mobile,
    marketingStatusLabel: seed.marketingStatusLabel,
    marketingEligible: marketingEligible(seed.marketingStatusLabel),
    locationName: LOCATIONS[seed.locationIndex],
    capturedAt: daysAgoIso(seed.capturedDaysAgo, referenceMs),
    needsRecovery: seed.needsRecovery,
    latestFeedbackSentiment: seed.latestFeedbackSentiment,
    feedbackSubmissionCount: seed.feedbackSubmissionCount,
    hasOffer: seed.hasOffer,
    offerRedeemedAt:
      seed.offerRedeemedDaysAgo == null
        ? null
        : daysAgoIso(seed.offerRedeemedDaysAgo, referenceMs),
    lastInteractionAt:
      seed.lastInteractionDaysAgo == null
        ? null
        : daysAgoIso(seed.lastInteractionDaysAgo, referenceMs),
    lastInteractionLabel: "Feedback submitted",
  }
}

